export function formatSceneColorsModule(sceneColors: Record<string, string>): string {
  const entries = Object.entries(sceneColors)
    .map(([name, hex]) => `  ${name}: '${hex}',\n`)
    .join('');

  return `// Generated by this package's codegen script from the scene colour tokens in @vers/panda-preset.
// Change a colour in the preset, not here.
export const sceneColors = {
${entries}} as const;
`;
}
